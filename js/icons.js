/**
 * Replaces every <i data-lucide="name"> with an inline <svg>. Runs entirely
 * from the ICONS table above — nothing is fetched from the network.
 */
export function paintIcons(){
  document.querySelectorAll('[data-lucide]').forEach(el => {
    const name = el.getAttribute('data-lucide');
    const inner = ICONS[name];
    if (!inner) return;
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', '24');
    svg.setAttribute('height', '24');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    const extraClass = el.getAttribute('class');
    if (extraClass) svg.setAttribute('class', extraClass);
    svg.innerHTML = inner; // static, developer-authored markup only — never user input
    el.replaceWith(svg);
  });
}
